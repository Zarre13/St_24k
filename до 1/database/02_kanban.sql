CREATE SCHEMA IF NOT EXISTS kanban;

CREATE TABLE IF NOT EXISTS kanban.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kanban.boards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES kanban.users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS kanban.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo', 'in_progress', 'done')),
    priority INTEGER NOT NULL DEFAULT 0,
    board_id BIGINT NOT NULL REFERENCES kanban.boards(id) ON DELETE CASCADE,
    assignee_id BIGINT REFERENCES kanban.users(id) ON DELETE SET NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_kanban_tasks_board_id ON kanban.tasks (board_id);
CREATE INDEX IF NOT EXISTS ix_kanban_tasks_status ON kanban.tasks (status);
CREATE INDEX IF NOT EXISTS ix_kanban_boards_owner_id ON kanban.boards (owner_id);
CREATE INDEX IF NOT EXISTS ix_kanban_tasks_board_status
    ON kanban.tasks (board_id, status) WHERE NOT is_deleted;

CREATE OR REPLACE FUNCTION kanban.set_task_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tasks_set_updated_at ON kanban.tasks;
CREATE TRIGGER tasks_set_updated_at
BEFORE UPDATE ON kanban.tasks
FOR EACH ROW
EXECUTE FUNCTION kanban.set_task_updated_at();

CREATE OR REPLACE VIEW kanban.board_task_statistics AS
SELECT
    b.id AS board_id,
    b.title AS board_title,
    COUNT(t.id) FILTER (WHERE t.status = 'todo') AS todo_count,
    COUNT(t.id) FILTER (WHERE t.status = 'in_progress') AS in_progress_count,
    COUNT(t.id) FILTER (WHERE t.status = 'done') AS done_count,
    COUNT(t.id) AS total_count
FROM kanban.boards AS b
LEFT JOIN kanban.tasks AS t
    ON t.board_id = b.id AND NOT t.is_deleted
GROUP BY b.id, b.title;
