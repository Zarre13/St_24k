CREATE SCHEMA IF NOT EXISTS booking;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS booking.resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS booking.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES booking.resources(id),
    user_id BIGINT NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    during TSTZRANGE GENERATED ALWAYS AS
        (tstzrange(start_time, end_time, '[)')) STORED,
    status TEXT NOT NULL DEFAULT 'confirmed'
        CHECK (status IN ('confirmed', 'cancelled', 'expired')),
    CONSTRAINT bookings_positive_duration CHECK (end_time > start_time),
    CONSTRAINT bookings_no_confirmed_overlap
        EXCLUDE USING gist (resource_id WITH =, during WITH &&)
        WHERE (status = 'confirmed')
);

CREATE INDEX IF NOT EXISTS ix_bookings_user_id ON booking.bookings (user_id);
CREATE INDEX IF NOT EXISTS ix_bookings_start_time ON booking.bookings (start_time);
CREATE INDEX IF NOT EXISTS ix_bookings_resource_status
    ON booking.bookings (resource_id, status);

CREATE OR REPLACE PROCEDURE booking.cancel_expired_bookings()
LANGUAGE SQL
AS $$
    UPDATE booking.bookings
    SET status = 'expired'
    WHERE status = 'confirmed'
      AND end_time <= now()
$$;
