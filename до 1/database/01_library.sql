CREATE SCHEMA IF NOT EXISTS library;

CREATE TABLE IF NOT EXISTS library.authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    birth_year INTEGER CHECK (birth_year BETWEEN 1 AND 2100)
);

CREATE TABLE IF NOT EXISTS library.genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS library.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    isbn VARCHAR(20) UNIQUE,
    published_year INTEGER CHECK (published_year BETWEEN 1 AND 2100),
    author_id BIGINT REFERENCES library.authors(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS library.books_genres (
    book_id BIGINT NOT NULL REFERENCES library.books(id) ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES library.genres(id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, genre_id)
);

CREATE INDEX IF NOT EXISTS ix_books_published_year
    ON library.books (published_year);
CREATE INDEX IF NOT EXISTS ix_books_author_id
    ON library.books (author_id);
CREATE INDEX IF NOT EXISTS ix_books_genres_genre_id
    ON library.books_genres (genre_id, book_id);
